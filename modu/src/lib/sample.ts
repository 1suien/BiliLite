/** 一张 600×900 的示例封面（canvas 画，避开版权素材） */
function makeCoverPng(title: string): Promise<Uint8Array> {
  const canvas = document.createElement('canvas')
  canvas.width = 600
  canvas.height = 900
  const ctx = canvas.getContext('2d')!
  const g = ctx.createLinearGradient(0, 0, 0, 900)
  g.addColorStop(0, '#2f4a5f')
  g.addColorStop(0.55, '#1d2f3d')
  g.addColorStop(1, '#0e1720')
  ctx.fillStyle = g
  ctx.fillRect(0, 0, 600, 900)
  // 月亮
  ctx.fillStyle = 'rgba(255, 246, 219, 0.92)'
  ctx.beginPath()
  ctx.arc(430, 190, 58, 0, Math.PI * 2)
  ctx.fill()
  // 海面与灯塔光
  ctx.fillStyle = 'rgba(255, 240, 200, 0.10)'
  ctx.beginPath()
  ctx.moveTo(0, 700)
  ctx.lineTo(600, 640)
  ctx.lineTo(600, 900)
  ctx.lineTo(0, 900)
  ctx.closePath()
  ctx.fill()
  ctx.strokeStyle = 'rgba(255, 232, 180, 0.55)'
  ctx.lineWidth = 2
  ctx.beginPath()
  ctx.moveTo(0, 700)
  ctx.lineTo(600, 640)
  ctx.stroke()
  // 标题
  ctx.fillStyle = '#f6efe3'
  ctx.font = '600 74px "Songti SC", "Noto Serif CJK SC", serif'
  ctx.textAlign = 'center'
  ctx.fillText(title, 300, 470)
  ctx.strokeStyle = 'rgba(246, 239, 227, 0.45)'
  ctx.lineWidth = 1.5
  ctx.beginPath()
  ctx.moveTo(210, 515)
  ctx.lineTo(390, 515)
  ctx.stroke()

  const dataUrl = canvas.toDataURL('image/png')
  const b64 = dataUrl.slice(dataUrl.indexOf(',') + 1)
  const bin = atob(b64)
  const out = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i)
  return Promise.resolve(out)
}

/** 现场生成一本示例 EPUB（nav 目录 + 三章 + 内嵌图片 + 封面） */
export async function buildSampleEpub(): Promise<ArrayBuffer> {
  const cover = await makeCoverPng('岛上灯塔')
  const zip = new JSZip()

  zip.file(
    'mimetype',
    'application/epub+zip',
    { compression: 'STORE' } as JSZip.JSZipFileOptions,
  )

  zip.file(
    'META-INF/container.xml',
    `<?xml version="1.0" encoding="UTF-8"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles>
    <rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/>
  </rootfiles>
</container>`,
  )

  const chapters = [
    { id: 'ch1', title: '第一章 潮声', body: SAMPLE_TXT_TEXT.split('第二章')[0].split('\n').slice(1).join('\n') },
    { id: 'ch2', title: '第二章 灯塔', body: SAMPLE_TXT_TEXT.split('第二章')[1].split('第三章')[0].split('\n').slice(1).join('\n') },
    { id: 'ch3', title: '第三章 来信', body: SAMPLE_TXT_TEXT.split('第三章')[1].split('第四章')[0].split('\n').slice(1).join('\n') },
    {
      id: 'ch4',
      title: '第四章 归途',
      body:
        SAMPLE_TXT_TEXT.split('第四章')[1].split('\n').slice(1).join('\n') +
        '\n最后，他在海图志的扉页写下一行字：灯亮着，就总会有人回来。',
    },
  ]

  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  const paras = (s: string) =>
    s
      .split('\n')
      .map((l) => l.trim())
      .filter(Boolean)
      .map((l) => `<p>${esc(l)}</p>`)
      .join('\n      ')

  for (const ch of chapters) {
    zip.file(
      `OEBPS/text/${ch.id}.xhtml`,
      `<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops" xml:lang="zh-CN" lang="zh-CN">
<head><title>${ch.title}</title><link rel="stylesheet" type="text/css" href="../styles/book.css"/></head>
<body>
  <h2>${ch.title}</h2>
  ${paras(ch.body)}
  ${ch.id === 'ch2' ? '<div class="figure"><img src="../images/sea.png" alt="海"/><p class="cap">图：海上的光</p></div>' : ''}
</body>
</html>`,
    )
  }

  zip.file(
    'OEBPS/styles/book.css',
    `body { margin: 0; padding: 0.2em 0; text-align: justify; }
h2 { font-size: 1.3em; margin: 0.9em 0 0.7em; font-weight: 600; }
p { margin: 0 0 0.9em; text-indent: 2em; line-height: 1.85; }
.figure { margin: 1.1em 0; text-align: center; }
.figure img { max-width: 92%; border-radius: 6px; }
.cap { text-indent: 0; font-size: 0.82em; color: #7d7a72; margin-top: 0.4em; }`,
  )

  // 内嵌插图：和封面同源，避免外部素材
  zip.file('OEBPS/images/sea.png', cover)
  zip.file('OEBPS/images/cover.png', cover)

  zip.file(
    'OEBPS/content.opf',
    `<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="bookid">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="bookid">readawre-sample-epub</dc:identifier>
    <dc:title>岛上灯塔（EPUB 示例）</dc:title>
    <dc:creator>墨读示例</dc:creator>
    <dc:language>zh-CN</dc:language>
    <meta name="cover" content="cover-img"/>
  </metadata>
  <manifest>
    <item id="nav" href="text/nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>
    <item id="cover-img" href="images/cover.png" media-type="image/png" properties="cover-image"/>
    <item id="css" href="styles/book.css" media-type="text/css"/>
    <item id="sea" href="images/sea.png" media-type="image/png"/>
    <item id="ch1" href="text/ch1.xhtml" media-type="application/xhtml+xml"/>
    <item id="ch2" href="text/ch2.xhtml" media-type="application/xhtml+xml"/>
    <item id="ch3" href="text/ch3.xhtml" media-type="application/xhtml+xml"/>
    <item id="ch4" href="text/ch4.xhtml" media-type="application/xhtml+xml"/>
  </manifest>
  <spine>
    <itemref idref="ch1"/>
    <itemref idref="ch2"/>
    <itemref idref="ch3"/>
    <itemref idref="ch4"/>
  </spine>
</package>`,
  )

  zip.file(
    'OEBPS/text/nav.xhtml',
    `<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops">
<head><title>目录</title></head>
<body>
  <nav epub:type="toc" id="toc">
    <h1>目录</h1>
    <ol>
      ${chapters.map((c) => `<li><a href="${c.id}.xhtml">${c.title}</a></li>`).join('\n      ')}
    </ol>
  </nav>
</body>
</html>`,
  )

  return zip.generateAsync({ type: 'arraybuffer' })
}

/** 生成一份三页的极简 PDF（英文正文，Unicode 中文需要嵌字体，示例里不做） */
export function buildSamplePdf(): ArrayBuffer {
  const pages: string[][] = [
    ['MoDu - Sample PDF', '', 'This is a sample PDF generated for testing.', 'It has three pages of plain text.', 'Page 1'],
    ['The reader should render this with pdf.js.', '', 'You can pinch or use the +/- buttons', 'to zoom the page.', 'Page 2'],
    ['The last page.', '', 'If you can read this, the PDF pipeline works.', 'Page 3'],
  ]

  const objects: string[] = []
  const add = (s: string) => {
    objects.push(s)
    return objects.length
  }

  // 1: catalog, 2: pages, 3: font
  const fontId = 3
  const pageIds: number[] = []
  const contentIds: number[] = []

  // 占位，稍后回填 kids
  add('') // catalog (1)
  add('') // pages (2)
  add(`<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>`) // 3

  for (const lines of pages) {
    const ops: string[] = ['BT', '/F1 22 Tf', '1 0 0 1 72 760 Tm', '28 TL']
    lines.forEach((line, i) => {
      const escaped = line.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)')
      ops.push(i === 0 ? `(${escaped}) Tj` : `T* (${escaped}) Tj`)
    })
    ops.push('ET')
    const stream = ops.join('\n')
    const cid = add(`<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`)
    contentIds.push(cid)
    const pid = add(
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 ${fontId} 0 R >> >> /Contents ${cid} 0 R >>`,
    )
    pageIds.push(pid)
  }

  objects[0] = '<< /Type /Catalog /Pages 2 0 R >>'
  objects[1] = `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${pageIds.length} >>`

  let pdf = '%PDF-1.4\n'
  const offsets: number[] = []
  for (let i = 0; i < objects.length; i++) {
    offsets.push(pdf.length)
    pdf += `${i + 1} 0 obj\n${objects[i]}\nendobj\n`
  }
  const xrefPos = pdf.length
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`
  for (const off of offsets) {
    pdf += `${String(off).padStart(10, '0')} 00000 n \n`
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefPos}\n%%EOF\n`

  const bytes = new Uint8Array(pdf.length)
  for (let i = 0; i < pdf.length; i++) bytes[i] = pdf.charCodeAt(i) & 0xff
  return bytes.buffer
}
