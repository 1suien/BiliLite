/** 示例书正文（自写，避免版权问题），用于验收分页/目录/主题 */
export const SAMPLE_TXT_TEXT = `第一章 潮声

海雾在清晨漫上来，像一层薄薄的棉絮，把整座岛都裹住了。林舟站在礁石上，听见潮水在脚下碎开，一声接一声，仿佛有人在很远的地方敲门。他在这里守了三年灯塔，早已学会从潮声里分辨天气：声音闷而短，是要起风；声音清而长，是天要放晴。

灯塔的灯昨夜又闪了一次。他爬上塔顶，把灯罩擦干净，重新拧紧了那枚松动的螺丝。黄铜的灯座被海风吹得发乌，他用袖子一点点蹭亮，直到能在上面照见自己的眼睛。玻璃外是灰白色的海，渔船还没出港，只有几只海鸥贴着浪尖飞。

他把工具袋挎在肩上，顺着铁梯一级一级往下走。塔身被海雾浸得发凉，扶手上凝着一层细密的水珠。走到半路，他停下来，从衣袋里掏出半块干面包，掰了一小块丢给等在下面的阿墨。猫仰起头，尾巴尖轻轻一摆，像在道谢。

"这样的日子也不算坏。"他对自己说。岛上只有他一个人，一只叫阿墨的黑猫，还有一台老旧的收音机。收音机里偶尔能收到大陆的电台，女主持人用很温柔的声音念天气预报，念完就放一首老歌。林舟一般不听歌，他怕听了会想家。

午后岛上起了一阵短暂的太阳雨。雨点打在铁皮屋顶上，噼噼啪啪，像有人在上头撒豆子。林舟把门推开一条缝，让潮润的风进来，阿墨立刻凑过去，把鼻子贴在门缝上闻了很久。雨停的时候，海面上横着一道很淡的彩虹，断断续续的，像被谁用炭笔轻轻描了一笔。

第二章 灯塔

下午三点，风果然起来了。浪头打在防波堤上，溅起的水花有两人高。林舟把窗子一扇扇关好，检查了备用发电机的油量，然后坐回桌前，翻开那本翻了很多遍的《海图志》。书页已经发黄，边角卷起，里面对着这座岛只写了一行小字：无名屿，东经一百二十三度，孤悬海外，无居民。

无居民。他笑了笑。三年前他上岛的时候，这里确实连一间像样的屋子都没有，灯塔是旧的，屋子是塌的，补给船一个月才来一次。他花了整整一个春天把屋顶修好，把墙刷白，把窗框换成新的木头。阿墨就是那个春天来的，一只瘦得只剩骨架的小黑猫，蹲在门口叫了一夜，他开门把它抱了进来。

夜里十点，灯亮了。光束一圈一圈扫过海面，像一只缓慢转动的手，把黑暗推开一点点又收回来。林舟坐在塔下的台阶上，听见风从塔身的缝隙里挤过去，发出一种很低的呜呜声。他忽然想起小时候，母亲总在睡前给他留一盏小灯，说"有灯的地方就有人等你"。

他给自己泡了一杯浓茶，茶是上次补给带上来的，已经有些受潮，喝起来带着一点陈味。他就着茶把这周的日志补完：风向、气温、潮汐、灯的工作时长。写到最后一行，他停住笔，在备注栏里写了四个字：一切正常。这四个字他写了三年，每次落笔都很认真，像在向谁报一个平安。

第三章 来信

补给船是隔天上午到的。船长老周把两箱物资搬上岸，又从怀里掏出一个信封，说："大陆寄来的，说是你的信。"林舟愣住了。他在岛上三年，除了物资清单，没收到过任何纸做的东西。

信封上有熟悉的字迹，是他妹妹的。信很短，说母亲病了，不算太重，但总念叨他；说家里的老房子要拆了，问他还回不回来。信纸的末尾有一块淡淡的水渍，分不清是雨水还是别的什么。林舟把信读了三遍，放进口袋里，又拿出来读了一遍。

那天下午他没有去擦灯罩。他坐在礁石上，看潮水一点点退下去，露出湿漉漉的黑色石面。阿墨蹲在他脚边，尾巴一下一下地扫着他的裤腿。他想起母亲送他上船那天，站在码头上，风吹起她的头发，她什么也没说，只是一直挥手，直到船开出很远，远到只剩一个小小的影子。

第四章 归途

第二天一早，他给海事局打了电话，申请休假。接电话的人说，塔上不能没人，得等接班的人来。他说好，我等。他把灯塔从上到下打扫了一遍，把工具一件件摆回原位，把那本《海图志》放进抽屉，又把母亲的照片从墙上取下来，用手帕包好，放在行李箱最上面。

收拾到一半，他在抽屉最里头摸到一只铁皮盒子。打开，里面是一枚生了锈的灯塔钥匙、两颗纽扣，还有一张褪了色的船票。他把船票翻过来，背面的日期已经看不清了。他想了想，还是把盒子合上，放回原处——这里的东西，留给下一个人吧。

接班的人在第四天下午到了。是个很年轻的小伙子，眼睛里带着点紧张。林舟把钥匙交给他，带他走了一遍每天要走的路线：几点开灯，几点关灯，油量怎么看，螺丝松了怎么拧，风大的时候哪扇窗要加一道楔子。小伙子一直点头，到最后一句话也没说。

船离开岛的时候，天已经擦黑了。林舟站在船尾，看见灯塔的灯亮起来，第一圈光扫过海面，第二圈，第三圈。光里有一点点暖，像有人在很远的地方，替他把门留着。阿墨装在新买的笼子里，安静地趴在垫子上。他摸了摸笼子，轻声说："回家了。"
`

